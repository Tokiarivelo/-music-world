import { chromium } from 'playwright-core';
import { readFileSync } from 'node:fs';
const tpl = JSON.parse(readFileSync('../api/music_world/templates/infrastructure/featured/enchanted-realm.json', 'utf8'));
const id = '00000000-0000-7000-8000-000000000006';
const item = { id, template: tpl, status: 'published', author: { displayName: 'Music World' }, featured: true, thumbnailUrl: null, createdAt: '2026-11-26T00:00:00Z', publishedAt: '2026-11-26T00:00:00Z' };
const b = await chromium.launch({ executablePath: '/home/tokiarivelo/.cache/ms-playwright/chromium_headless_shell-1248/chrome-headless-shell-linux64/chrome-headless-shell', args: ['--use-gl=angle','--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist','--autoplay-policy=no-user-gesture-required'] });
const pg = await b.newPage({ viewport: { width: 1000, height: 620 } });
await pg.route(/\/api\/templates(\?.*)?$/, (r) => r.fulfill({ contentType: 'application/json', body: JSON.stringify({ items: [item], nextCursor: null }) }));
await pg.route(/\/api\/templates\/00000000.*/, (r) => r.fulfill({ contentType: 'application/json', body: JSON.stringify(item) }));
await pg.goto('http://localhost:3001/play/demo?template=' + id, { timeout: 120000 });
await pg.waitForTimeout(15000);
await pg.getByText('Skip', { exact: true }).click().catch(()=>{});
await pg.getByRole('button', { name: 'Play', exact: true }).first().click();
await pg.waitForTimeout(3000);
await pg.getByRole('button', { name: 'Explore', exact: true }).click().catch(()=>{});
await pg.mouse.move(500,300); await pg.mouse.wheel(0, -600);
await pg.waitForTimeout(30000);
await pg.screenshot({ path: '/tmp/claude-1000/-home-tokiarivelo-Documents-Projects-music-world-project/df0b6b2b-e3c1-4f33-8f68-d521ceb3238a/scratchpad/shot7.png', timeout: 170000 });
await b.close();
