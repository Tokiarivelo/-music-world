import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { NEON_NOCTURNE } from '@/templates/default';
import type { DirectorState } from '../hooks/use-director';
import { PROVIDERS, result } from '../test-fixtures';
import { DirectorPanel } from './DirectorPanel';

function state(over: Partial<DirectorState> = {}): DirectorState {
  return {
    status: 'idle',
    errorKey: null,
    providers: PROVIDERS.providers.filter((p) => p.configured),
    provider: 'muse',
    setProvider: vi.fn(),
    generate: vi.fn(),
    templates: [],
    results: [],
    latest: null,
    ...over,
  };
}

afterEach(cleanup);

describe('DirectorPanel', () => {
  it('offers configured providers and generates on click', () => {
    const director = state();
    render(<DirectorPanel director={director} template={NEON_NOCTURNE} />);
    const select = screen.getByLabelText('AI provider');
    expect([...select.querySelectorAll('option')].map((o) => o.textContent)).toEqual(['Meta Muse', 'Mock (offline)']);
    fireEvent.change(select, { target: { value: 'mock' } });
    expect(director.setProvider).toHaveBeenCalledWith('mock');
    fireEvent.click(screen.getByRole('button', { name: 'Generate world with AI' }));
    expect(director.generate).toHaveBeenCalled();
    expect(screen.queryByTestId('generated-by')).toBeNull();
  });

  it('labels a generated template and explains a fallback', () => {
    const r = result('mock', 'ai-mock-1', 'muse');
    render(<DirectorPanel director={state({ results: [r], latest: r })} template={r.template} />);
    expect(screen.getByTestId('generated-by').textContent).toBe('Generated by Mock (offline) · mock-director-1');
    expect(screen.getByText('Meta Muse was unavailable, so Mock (offline) answered.')).toBeTruthy();
  });

  it('renders model text as text, never as HTML', () => {
    const r = result('muse', 'ai-muse-1');
    const template = { ...r.template, name: '<img src=x onerror=alert(1)>' };
    const { container } = render(<DirectorPanel director={state({ results: [r] })} template={template} />);
    expect(container.querySelector('img')).toBeNull();
  });

  it('shows progress and errors, and disables the button while generating', () => {
    const { rerender } = render(<DirectorPanel director={state({ status: 'generating' })} template={NEON_NOCTURNE} />);
    expect(screen.getByRole('status').textContent).toBe('Generating your world…');
    expect((screen.getByRole('button') as HTMLButtonElement).disabled).toBe(true);
    rerender(
      <DirectorPanel director={state({ status: 'error', errorKey: 'RATE_LIMITED' })} template={NEON_NOCTURNE} />,
    );
    expect(screen.getByRole('alert').textContent).toBe('Too many worlds generated. Try again later.');
  });
});
