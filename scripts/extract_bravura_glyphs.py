"""Extract the SMuFL glyph outlines Music World draws from the Bravura font.

Writes `apps/web/src/xr/glyphs/bravura-outlines.ts` (04-default-template requirement 4.3): one SVG-like path per glyph
(M / L / Q / C / Z commands), in staff spaces (SMuFL: 1 em = 4 staff spaces), y up, origin as in the font
(notes: left of the notehead, notehead centred on y = 0; G clef: y = 0 on the G line).

Bravura is (c) Steinberg Media Technologies GmbH, licensed under the SIL Open Font License 1.1
(`assets/fonts/bravura/LICENSE.txt`). The outlines are used as rendered shapes; no font is generated.

Usage (needs fontTools): uv run --with fonttools python scripts/extract_bravura_glyphs.py
"""

from __future__ import annotations

from pathlib import Path

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "assets" / "fonts" / "bravura" / "Bravura.otf"
OUT = ROOT / "apps" / "web" / "src" / "xr" / "glyphs" / "bravura-outlines.ts"

# SMuFL names and code points (https://w3c.github.io/smufl/latest/).
GLYPHS: dict[str, int] = {
    "gClef": 0xE050,
    "noteQuarterUp": 0xE1D5,
    "noteEighthUp": 0xE1D7,
    "note16thUp": 0xE1D9,
}
STAFF_SPACES_PER_EM = 4


def fmt(v: float) -> str:
    text = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def glyph_path(font: TTFont, code_point: int, scale: float) -> tuple[str, float]:
    glyph_name = font.getBestCmap()[code_point]
    glyph_set = font.getGlyphSet()
    pen = RecordingPen()
    glyph_set[glyph_name].draw(pen)
    parts: list[str] = []
    for op, args in pen.value:
        pts = " ".join(f"{fmt(x * scale)} {fmt(y * scale)}" for x, y in args)
        if op == "moveTo":
            parts.append(f"M {pts}")
        elif op == "lineTo":
            parts.append(f"L {pts}")
        elif op == "qCurveTo":
            parts.append(f"Q {pts}")
        elif op == "curveTo":
            parts.append(f"C {pts}")
        elif op in ("closePath", "endPath"):
            parts.append("Z")
        else:
            raise ValueError(f"unsupported pen operation {op}")
    advance = font["hmtx"][glyph_name][0] * scale
    return " ".join(parts), advance


def main() -> None:
    font = TTFont(FONT)
    scale = STAFF_SPACES_PER_EM / font["head"].unitsPerEm
    version = font["name"].getDebugName(5)
    lines = [
        "// GENERATED by scripts/extract_bravura_glyphs.py from assets/fonts/bravura/Bravura.otf — do not edit.",
        f"// Bravura {version}, (c) Steinberg Media Technologies GmbH, SIL Open Font License 1.1",
        "// (assets/fonts/bravura/LICENSE.txt). Paths in staff spaces, y up (SMuFL origin).",
        "",
        "export interface GlyphOutline {",
        "  /** Advance width in staff spaces. */",
        "  readonly advance: number;",
        "  /** SVG-like path: M / L / Q / C / Z with absolute coordinates. */",
        "  readonly path: string;",
        "}",
        "",
        f"export type BravuraGlyphName = {' | '.join(repr(n) for n in GLYPHS)};",
        "",
        "export const BRAVURA_OUTLINES: Readonly<Record<BravuraGlyphName, GlyphOutline>> = {",
    ]
    for name, code_point in GLYPHS.items():
        path, advance = glyph_path(font, code_point, scale)
        lines.append(f"  {name}: {{")
        lines.append(f"    advance: {fmt(advance)},")
        lines.append(f"    path: '{path}',")
        lines.append("  },")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
